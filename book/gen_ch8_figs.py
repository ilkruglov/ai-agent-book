sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from svg_lib import FS_SMALL, FS_TINY, SVG, parse_output_dir

_output_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "images")


def _pipeline(
    stages: list[tuple[str, str]],
    fname: str,
    W: int = 880,
    feedback: str | None = None,
) -> None:
    """Горизонтальная последовательность этапов с необязательной пунктирной петлёй обратной связи."""
    n = len(stages)
    bw = min(190, (W - 40 - (n - 1) * 22) // n)
    bh, gap = 84, 22
    H = 234 if feedback else 174  # +24 для 40-пиксельного поля обрезки заголовка
    s = SVG(W, H)
    x0 = (W - (n * bw + (n - 1) * gap)) / 2
    y = 48  # начало ниже линии TITLE_CROP_PX=40
    pos: list[float] = []
    for i, (lab, sub) in enumerate(stages):
        x = x0 + i * (bw + gap)
        s.box(x, y, bw, bh, lab, sublabel=sub, bold=True, fill="light")
        pos.append(x)
        if i > 0:
            s.arrow(pos[i - 1] + bw + 2, y + bh / 2, x - 2, y + bh / 2)
    if feedback:
        lx = pos[-1] + bw / 2
        fx = pos[0] + bw / 2
        ry = y + bh + 34
        s.line(lx, y + bh, lx, ry, dash=True)
        s.line(lx, ry, fx, ry, dash=True)
        s.arrow(fx, ry, fx, y + bh + 2, dash=True)
        s.text(
            (lx + fx) / 2,
            ry + 18,
            feedback,
            size=FS_SMALL,
            fill="text_light",
            max_width=W - 20,
        )
    s.save(os.path.join(_output_dir, fname + ".svg"))


